# ==========================================
# SUMMARIES
# ==========================================

@router.post("/summaries", response_model=SummaryResponse, status_code=status.HTTP_201_CREATED)
async def create_summary(
    request: SummaryRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Generate an AI executive summary, key concepts, and terminology from a study document."""
    # Verify document ownership
    doc_stmt = select(Document).where(and_(Document.id == request.document_id, Document.user_id == current_user.id))
    doc_res = await db.execute(doc_stmt)
    if not doc_res.scalar_one_or_none():
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Document not found.")

    summary = await generate_document_summary(
        document_id=request.document_id,
        user_id=current_user.id,
        focus_area=request.focus_area or "Comprehensive",
        db=db
    )
    return summary


@router.get("/summaries", response_model=List[SummaryResponse])
async def list_summaries(
    document_id: Optional[str] = None,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """List all generated summaries for the user."""
    stmt = select(Summary).where(Summary.user_id == current_user.id).order_by(Summary.created_at.desc())
    if document_id:
        stmt = stmt.where(Summary.document_id == document_id)
    result = await db.execute(stmt)
    return result.scalars().all()


