@router.post("/flashcards", response_model=List[FlashcardItem], status_code=status.HTTP_201_CREATED)
async def create_flashcards(
    request: FlashcardRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Generate high-yield study flashcards from an indexed document."""
    doc_stmt = select(Document).where(and_(Document.id == request.document_id, Document.user_id == current_user.id))
    doc_res = await db.execute(doc_stmt)
    if not doc_res.scalar_one_or_none():
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Document not found.")

    flashcards = await generate_document_flashcards(
        document_id=request.document_id,
        user_id=current_user.id,
        num_cards=request.num_cards,
        category=request.category or "Key Concepts",
        db=db
    )
    return flashcards


@router.get("/flashcards", response_model=List[FlashcardItem])
async def list_flashcards(
    document_id: Optional[str] = None,
    category: Optional[str] = None,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """List all flashcards for the user."""
    stmt = select(Flashcard).where(Flashcard.user_id == current_user.id).order_by(Flashcard.created_at.desc())
    if document_id:
        stmt = stmt.where(Flashcard.document_id == document_id)
    if category:
        stmt = stmt.where(Flashcard.category == category)
    result = await db.execute(stmt)
    return result.scalars().all()


@router.delete("/flashcards/{flashcard_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_flashcard(
    flashcard_id: str,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Delete a flashcard."""
    stmt = select(Flashcard).where(and_(Flashcard.id == flashcard_id, Flashcard.user_id == current_user.id))
    result = await db.execute(stmt)
    fc = result.scalar_one_or_none()
    if not fc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Flashcard not found.")
    await db.delete(fc)
    await db.commit()
    return None
