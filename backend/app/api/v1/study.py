@router.post("/quizzes/{quiz_id}/submit", response_model=QuizResultResponse)
async def submit_quiz(
    quiz_id: str,
    submission: QuizSubmitRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Submit quiz answers, grade in real-time, and return score & detailed answer explanations."""
    stmt = select(Quiz).where(and_(Quiz.id == quiz_id, Quiz.user_id == current_user.id))
    result = await db.execute(stmt)
    quiz = result.scalar_one_or_none()
    if not quiz:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Quiz not found.")

    answers_map = {a.question_id: a.selected_option for a in submission.answers}
    correct_count = 0
    details = []

    for q in quiz.questions:
        q_id = q.get("id")
        correct_ans = q.get("correct_answer")
        user_ans = answers_map.get(q_id, -1)
        is_correct = (user_ans == correct_ans)
        
        if is_correct:
            correct_count += 1

        details.append({
            "question_id": q_id,
            "question": q.get("question"),
            "options": q.get("options", []),
            "selected_option": user_ans,
            "correct_option": correct_ans,
            "is_correct": is_correct,
            "explanation": q.get("explanation", "")
        })

    total = len(quiz.questions) or 1
    score_pct = round((correct_count / total) * 100.0, 1)

    if score_pct >= 90:
        feedback = "Outstanding! You have thoroughly mastered these core concepts."
    elif score_pct >= 70:
        feedback = "Great work! Review the explanations for any missed questions to solidify your understanding."
    elif score_pct >= 50:
        feedback = "Good effort. Consider re-reading the highlighted chapters and asking the AI Chat for clarifications."
    else:
        feedback = "Keep practicing. We recommend reviewing the generated summary and flashcards before retrying."

    return {
        "quiz_id": quiz_id,
        "total_questions": total,
        "correct_count": correct_count,
        "score_percentage": score_pct,
        "feedback": feedback,
        "details": details
    }


